"""
Scientific & Game Balancing Catalog for ASTROMISSION.
Loads scenario and simulation rules dynamically from JSON configuration files in
backend/app/config/ (moon_scenario.json, mars_scenario.json, facilities.json, events.json).
"""
import json
from pathlib import Path
from typing import Dict, List, Any

_CONFIG_DIR = Path(__file__).resolve().parent.parent / "config"


def _load_json_config(filename: str, fallback: Any) -> Any:
    path = _CONFIG_DIR / filename
    if path.exists():
        try:
            return json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            return fallback
    return fallback


